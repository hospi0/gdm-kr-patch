def main():
    lines = [l.rstrip('\n').split('\t') for l in open('work/trans/shrink_fail.txt', encoding='utf-8')]
    runs = list(csv.DictReader(open('work/trans/runs.tsv.merged3', encoding='utf-8'), delimiter='\t'))
    idx = {(r['file'], r['off']): i for i, r in enumerate(runs)}

    ok = bad = 0
    fails = []
    for i, (f, off, L, oldko) in enumerate(lines):
        L = int(L)
        newko = NEW.get(i)
        if newko is None:
            fails.append((i, f, off, L, oldko, 'NO_ENTRY'))
            bad += 1
            continue
        try:
            n = len(encode(newko, rev, ko))
        except BuildError as e:
            fails.append((i, f, off, L, newko, 'ENC:' + str(e)))
            bad += 1
            continue
        if n > L:
            fails.append((i, f, off, L, newko, 'OVER:%d' % (n - L)))
            bad += 1
            continue
        ri = idx.get((f, off))
        if ri is None:
            fails.append((i, f, off, L, newko, 'NOKEY'))
            bad += 1
            continue
        runs[ri]['ko'] = newko
        ok += 1

    print('적용 %d / 실패 %d' % (ok, bad))
    with open('work/trans/runs.tsv.merged4', 'w', encoding='utf-8', newline='') as fp:
        w = csv.writer(fp, delimiter='\t')
        w.writerow(['file', 'off', 'len', 'ja', 'ko'])
        for r in runs:
            w.writerow([r['file'], r['off'], r['len'], r['ja'], r['ko']])
    with open('work/trans/manual_shrink_fail.txt', 'w', encoding='utf-8') as f:
        for x in fails:
            f.write(repr(x) + '\n')
    print('저장: runs.tsv.merged4 / manual_shrink_fail.txt (%d건)' % len(fails))


if __name__ == '__main__':
    main()
