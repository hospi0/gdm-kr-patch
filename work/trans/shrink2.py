rev, ko = load_maps()
path = 'work/trans/runs.tsv'
rows = list(csv.reader(open(path, encoding='utf-8'), delimiter='\t'))
header, data = rows[0], rows[1:]

applied = fail = 0
for i, cands in CAND.items():
    L = int(data[i][2])
    chosen = None
    for c in cands:
        try:
            n = len(encode(c, rev, ko))
        except BuildError:
            continue
        if n <= L:
            chosen = c
            break
    if chosen is None:
        print('★미해결 idx=%d L=%d 후보전부실패: %s' % (i, L, cands))
        fail += 1
        continue
    data[i][4] = chosen
    applied += 1

print('적용 %d / 실패 %d' % (applied, fail))
if fail == 0:
    with open(path, 'w', encoding='utf-8', newline='') as fp:
        w = csv.writer(fp, delimiter='\t')
        w.writerow(header)
        w.writerows(data)
    print('runs.tsv 갱신 완료')
