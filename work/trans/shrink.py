assert len(IDX) == len(NEW) == 234, (len(IDX), len(NEW))

rev, ko = load_maps()

path = 'work/trans/runs.tsv'
rows = list(csv.reader(open(path, encoding='utf-8'), delimiter='\t'))
header, data = rows[0], rows[1:]

byidx = dict(zip(IDX, NEW))
applied = fail = 0
for i, r in enumerate(data):
    if i in byidx:
        newko = byidx[i]
        L = int(r[2])
        try:
            n = len(encode(newko, rev, ko))
        except BuildError as e:
            print('★인코딩 실패 idx=%d: %s (%s)' % (i, e, newko))
            fail += 1
            continue
        if n > L:
            print('★여전히 초과 idx=%d: %dB > %dB  %s' % (i, n, L, newko))
            fail += 1
            continue
        r[4] = newko
        applied += 1

print('적용 %d / 실패 %d' % (applied, fail))
if fail == 0:
    with open(path, 'w', encoding='utf-8', newline='') as fp:
        w = csv.writer(fp, delimiter='\t')
        w.writerow(header)
        w.writerows(data)
    print('runs.tsv 갱신 완료')
