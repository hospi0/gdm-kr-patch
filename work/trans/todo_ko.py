def main():
    rev, ko = load_maps()
    rows = list(csv.DictReader(open('work/trans/runs.tsv', encoding='utf-8'), delimiter='\t'))
    idx = {(r['file'], r['off']): i for i, r in enumerate(rows)}
    todo = []
    for line in open('work/trans/todo.txt', encoding='utf-8'):
        p = line.rstrip('\n').split('\t')
        if len(p) == 5 and p[0].isdigit():
            todo.append((int(p[0]), p[1], p[2], int(p[3]), p[4]))

    ok = skip = bad = 0
    fails = []
    for i, f, off, L, ja in todo:
        t = KO.get(i)
        if t is None:
            skip += 1
            continue
        try:
            n = len(encode(t, rev, ko))
        except BuildError as e:
            fails.append((i, f, off, L, t, str(e)))
            bad += 1
            continue
        if n > L:
            fails.append((i, f, off, L, t, 'OVER:%d' % (n - L)))
            bad += 1
            continue
        rows[idx[(f, off)]]['ko'] = t
        ok += 1
    print('적용 %d / 미번역유지 %d / 실패 %d' % (ok, skip, bad))
    with open('work/trans/runs.tsv', 'w', encoding='utf-8', newline='') as fp:
        w = csv.writer(fp, delimiter='\t')
        w.writerow(['file', 'off', 'len', 'ja', 'ko'])
        for r in rows:
            w.writerow([r['file'], r['off'], r['len'], r['ja'], r['ko']])
    with open('work/trans/todo_fail.txt', 'w', encoding='utf-8') as fp:
        for x in fails:
            fp.write(repr(x) + '\n')
    print('실패 목록: work/trans/todo_fail.txt')


if __name__ == '__main__':
    main()
